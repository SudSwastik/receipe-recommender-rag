def _get_variant_prefix(tags: list, variation_index: int) -> str:
    for tag in tags:
        if tag in VARIANT_PREFIXES_BY_TAG:
            pool = VARIANT_PREFIXES_BY_TAG[tag]
            return pool[(variation_index - 1) % len(pool)]
    fallbacks = ["Classic", "Traditional", "Home-Style", "Family"]
    return fallbacks[(variation_index - 1) % len(fallbacks)]

def _scale_quantity(text: str, factor: float) -> str:
    """Best-effort numeric scaling of the first number found in a string."""
    import re
    def replacer(m):
        val = float(m.group())
        scaled = val * factor
        if scaled == int(scaled):
            return str(int(scaled))
        return f"{scaled:.1f}".rstrip("0").rstrip(".")
    return re.sub(r"\d+(?:\.\d+)?", replacer, text, count=1)


def generate_variation(base: dict, variation_index: int) -> dict:
    recipe = copy.deepcopy(base)
    rng = random.Random(id(base["title"]) + variation_index)

    # Scale servings
    new_serves = rng.choice(SERVING_OPTIONS)
    scale = new_serves / base["serves"]
    recipe["serves"] = new_serves
    recipe["ingredients"] = [_scale_quantity(i, scale) for i in base["ingredients"]]

    # Swap one herb
    for herb, subs in HERB_SUBS.items():
        for i, ingredient in enumerate(recipe["ingredients"]):
            if herb in ingredient.lower():
                sub = rng.choice(subs)
                recipe["ingredients"][i] = ingredient.lower().replace(herb, sub)
                break

    # Real culinary variant title — no "(Variation X)" labels
    if variation_index > 0:
        prefix = _get_variant_prefix(base["tags"], variation_index)
        recipe["title"] = f"{prefix} {base['title']}"

    return recipe



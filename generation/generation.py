def _recipe_to_text(recipe: dict) -> str:
    tags = ", ".join(recipe["tags"])
    lines = [
        f"Title: {recipe['title']}",
        f"Tags: {tags}",
        f"Prep: {recipe['prep_min']} min  |  Cook: {recipe['cook_min']} min  |  Serves: {recipe['serves']}",
        "",
        "## Ingredients",
    ]
    for ing in recipe["ingredients"]:
        lines.append(ing)
    lines += ["", "## Method"]
    for i, step in enumerate(recipe["method"], 1):
        lines.append(f"{i}. {step}")
    lines += ["", "## Chef Tips"]
    for tip in recipe["tips"]:
        lines.append(f"- {tip}")
    lines.append("")
    return "\n".join(lines)


